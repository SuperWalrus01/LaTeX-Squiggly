#!/usr/bin/env python3
"""
Generates the Android app's launcher icons from assets/app-icon.png.

Two kinds. mipmap-*/ic_launcher.png is the whole icon, square, for launchers
that draw icons as they are. The adaptive icon, which Android 8 and later
prefer, is the wordmark on its own on a transparent foreground, with the
icon's cream as the background colour: launchers mask an adaptive icon to a
circle or a squircle and keep only the middle 72 of its 108 dp, so the
wordmark is shrunk to sit inside that.

Needs Pillow.  Run:  python3 scripts/make-android-icons.py
"""

import os, sys

try:
    from PIL import Image
except ImportError:
    sys.exit("needs Pillow: python3 -m pip install Pillow")

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SOURCE = os.path.join(ROOT, "assets", "app-icon.png")
RES = os.path.join(ROOT, "android", "app", "src", "main", "res")

# Launcher icon sizes in pixels, by density: 48 dp each.
LEGACY = {"mdpi": 48, "hdpi": 72, "xhdpi": 96, "xxhdpi": 144, "xxxhdpi": 192}
# The adaptive foreground is 108 dp; xxxhdpi only, which Android scales down.
FOREGROUND = 432
# The wordmark's width as a share of the foreground, inside the 66% circle
# every mask keeps.
ARTWORK = 0.62


def main():
    icon = Image.open(SOURCE).convert("RGB")
    background = icon.getpixel((4, 4))

    for density, size in LEGACY.items():
        folder = os.path.join(RES, f"mipmap-{density}")
        os.makedirs(folder, exist_ok=True)
        icon.resize((size, size), Image.LANCZOS).save(os.path.join(folder, "ic_launcher.png"), optimize=True)

    # The wordmark: everything that is not the background, cropped to itself.
    rgba = icon.convert("RGBA")
    pixels = rgba.load()
    for y in range(rgba.height):
        for x in range(rgba.width):
            r, g, b, _ = pixels[x, y]
            distance = max(abs(r - background[0]), abs(g - background[1]), abs(b - background[2]))
            pixels[x, y] = (r, g, b, min(255, distance * 4))
    mark = rgba.crop(rgba.getbbox())
    scale = FOREGROUND * ARTWORK / max(mark.width, mark.height)
    mark = mark.resize((round(mark.width * scale), round(mark.height * scale)), Image.LANCZOS)
    foreground = Image.new("RGBA", (FOREGROUND, FOREGROUND), (0, 0, 0, 0))
    foreground.paste(mark, ((FOREGROUND - mark.width) // 2, (FOREGROUND - mark.height) // 2), mark)
    folder = os.path.join(RES, "mipmap-xxxhdpi")
    foreground.save(os.path.join(folder, "ic_launcher_foreground.png"), optimize=True)

    folder = os.path.join(RES, "mipmap-anydpi-v26")
    os.makedirs(folder, exist_ok=True)
    with open(os.path.join(folder, "ic_launcher.xml"), "w", encoding="utf-8") as handle:
        handle.write("""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/make-android-icons.py. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background" />
    <foreground android:drawable="@mipmap/ic_launcher_foreground" />
    <monochrome android:drawable="@mipmap/ic_launcher_foreground" />
</adaptive-icon>
""")
    with open(os.path.join(RES, "values", "ic_launcher_background.xml"), "w", encoding="utf-8") as handle:
        handle.write(f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/make-android-icons.py: the cream of assets/app-icon.png. -->
<resources>
    <color name="ic_launcher_background">#{background[0]:02X}{background[1]:02X}{background[2]:02X}</color>
</resources>
""")
    print(f"generated {len(LEGACY)} launcher icons and the adaptive icon")


if __name__ == "__main__":
    main()
