#!/usr/bin/env python3
"""
Generates android/engine/src/main/kotlin/.../Tables.g.kt from the Swift
engine's own tables.

The same reasoning as scripts/generate-js-tables.py: the Android app has to
hold the same symbols, scripts and refusal messages as every other platform,
and a table transcribed by hand drifts the first time somebody adds a symbol
to one side. `latex-squiggly --dump-tables` prints the tables the Swift engine
uses at runtime, and this writes them out as Kotlin.

Every non-ASCII character is written as a \\u escape, so the file is pure
ASCII and reads the same whatever an editor guesses its encoding to be.

Run:  swift build && python3 scripts/generate-kotlin-tables.py

Without a Swift toolchain, --dump FILE reads a saved `--dump-tables` output
instead. The drift check in scripts/check-all.sh always uses the binary.
"""

import argparse, json, os, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "android", "engine", "src", "main", "kotlin",
                   "io", "github", "superwalrus01", "squiggly", "engine", "Tables.g.kt")

HEADER = """// Generated by scripts/generate-kotlin-tables.py from the Swift engine's own
// tables, via `latex-squiggly --dump-tables`. Do not edit by hand: edit the
// Swift side and regenerate, or the platforms drift apart.

package io.github.superwalrus01.squiggly.engine
"""


def literal(text):
    """A Kotlin string literal, ASCII only. Characters outside the basic plane
    become their UTF-16 surrogate pair, which is how Kotlin strings hold them."""
    out = []
    data = text.encode("utf-16-be")
    for i in range(0, len(data), 2):
        code = (data[i] << 8) | data[i + 1]
        ch = chr(code)
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "$":
            out.append("\\$")
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\t":
            out.append("\\t")
        elif 0x20 <= code < 0x7F:
            out.append(ch)
        else:
            out.append("\\u%04x" % code)
    return '"' + "".join(out) + '"'


def string_map(name, table, comment, key=literal):
    lines = [f"    /** {comment} */", f"    val {name}: Map<{'Int' if key is int_key else 'String'}, String> = mapOf("]
    for k in sorted(table, key=(lambda k: int(k)) if key is int_key else None):
        lines.append(f"        {key(k)} to {literal(table[k])},")
    lines.append("    )")
    return "\n".join(lines)


def int_key(k):
    return str(int(k))


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--dump", help="a saved `latex-squiggly --dump-tables` output")
    args = parser.parse_args()

    if args.dump:
        with open(args.dump, encoding="utf-8") as handle:
            tables = json.load(handle)
    else:
        binary = os.path.join(ROOT, ".build", "debug", "latex-squiggly")
        if not os.path.exists(binary):
            sys.exit("build the Swift engine first: swift build")
        tables = json.loads(subprocess.check_output([binary, "--dump-tables"]))

    parts = [HEADER, "/** One row of the coverage table, in the order the Swift engine lists it. */",
             "class SymbolEntry(val command: String, val glyph: String, val category: String, val unicodeName: String)",
             "", "internal object Tables {", ""]
    parts.append("    val entries: List<SymbolEntry> = listOf(")
    for e in tables["entries"]:
        parts.append(f"        SymbolEntry({literal(e['command'])}, {literal(e['glyph'])}, "
                     f"{literal(e['category'])}, {literal(e['unicodeName'])}),")
    parts.append("    )")
    parts.append("")
    parts.append(string_map("operators", tables["operators"], "\\sin, \\log, ... as upright text."))
    parts.append("")
    parts.append(string_map("unsupportedReasons", tables["unsupportedReasons"],
                            "Recognised but refused, with the reason the user is told."))
    parts.append("")
    parts.append(string_map("escapedLiterals", tables["escapedLiterals"], "\\# and friends."))
    parts.append("")
    parts.append(string_map("symbolReasons", tables["symbolReasons"],
                            "Control symbols that are refused, such as \\, and \\!."))
    parts.append("")
    parts.append(string_map("superscripts", tables["superscripts"], "Superscript forms."))
    parts.append("")
    parts.append(string_map("subscripts", tables["subscripts"], "Subscript forms."))
    parts.append("")
    parts.append(string_map("radicals", tables["radicals"], "Radical signs by index.", key=int_key))
    parts.append("")
    parts.append(string_map("vulgarFractions", tables["vulgarFractions"],
                            "Single-character fractions, keyed numerator/denominator."))
    parts.append("")
    parts.append(f"    const val FRACTION_SLASH: String = {literal(tables['fractionSlash'])}")
    parts.append("}")

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="ascii", newline="\n") as handle:
        handle.write("\n".join(parts) + "\n")

    print(f"generated {len(tables['entries'])} symbols, "
          f"{len(tables['superscripts'])} superscripts, "
          f"{len(tables['subscripts'])} subscripts, "
          f"{len(tables['vulgarFractions'])} fractions, "
          f"{len(tables['operators'])} operators, "
          f"{len(tables['unsupportedReasons'])} refusals")


if __name__ == "__main__":
    main()
